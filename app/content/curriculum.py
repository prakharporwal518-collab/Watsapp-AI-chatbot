def _build() -> tuple[dict[str, Topic], list[Module]]:
    topics: dict[str, Topic] = {}
    modules: list[Module] = []
    counters: dict[str, int] = {}
    for track, module_name, quiz_cat, items in _RAW:
        module = Module(track=track, name=module_name, quiz_category=quiz_cat)
        for item in items:
            slug, title, level, summary, keywords = item[:5]
            prereqs = item[5] if len(item) > 5 else ()
            counters[track] = counters.get(track, 0) + 1
            topic_id = f"{track}.{slug}"
            topic = Topic(
                id=topic_id,
                track=track,
                module=module_name,
                title=title,
                summary=summary,
                level=level,
                keywords=tuple(k.lower() for k in keywords),
                prerequisites=tuple(f"{track}.{p}" for p in prereqs),
                quiz_category=_category_for(track, slug, quiz_cat),
                order_index=counters[track],
            )
            topics[topic_id] = topic
            module.topics.append(topic)
        modules.append(module)
    return topics, modules


def _category_for(track: str, slug: str, module_cat: str | None) -> str | None:
    """Map a topic to the quiz category that holds its questions."""
    specific = {
        "arrays": "arrays_strings", "strings": "arrays_strings", "arrays_strings_basics": "arrays_strings",
        "linked_list": "linked_lists", "doubly_linked_list": "linked_lists", "circular_linked_list": "linked_lists",
        "stack": "stack_queue", "queue": "stack_queue", "circular_queue": "stack_queue",
        "hash_table": "arrays_strings", "hash_map": "arrays_strings", "sets": "arrays_strings",
        "two_pointers": "arrays_strings", "sliding_window": "arrays_strings", "prefix_sum": "arrays_strings",
        "kadane": "dynamic_programming", "dynamic_programming": "dynamic_programming",
        "greedy": "dsa_fundamentals", "backtracking": "dsa_fundamentals",
        "graph_traversal": "trees_graphs", "bfs_dfs": "trees_graphs", "dijkstra": "trees_graphs",
        "topological_sort": "trees_graphs", "shortest_paths": "trees_graphs",
        "interview_patterns": "dsa_fundamentals", "interview_easy_medium_hard": "dsa_fundamentals",
        "interview_strategy": "dsa_fundamentals",
    }
    if track == "dsa" and slug in specific:
        return specific[slug]
    if track == "ml" and slug.startswith("project_"):
        return "ml_algorithms"
    return module_cat


