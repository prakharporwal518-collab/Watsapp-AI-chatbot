"""The full curriculum: tracks → modules → topics.

Topic order inside a track is the recommended learning order. `keywords` help the
natural-language router match messages like "teach me two pointer technique".
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Topic:
    id: str
    track: str
    module: str
    title: str
    summary: str
    level: str = "beginner"
    keywords: tuple[str, ...] = ()
    prerequisites: tuple[str, ...] = ()
    quiz_category: str | None = None
    order_index: int = 0


@dataclass
class Module:
    track: str
    name: str
    quiz_category: str | None
    topics: list[Topic] = field(default_factory=list)


